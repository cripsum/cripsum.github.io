/** Un testo delle pagine per scrivere, con i valori al posto dei %s / %d. */
function cp_w(string $key, string $lang, mixed ...$args): string
{
    $text = cp_write_strings($lang)[$key] ?? $key;
    if (is_array($text)) $text = $text[0];
    return $args ? vsprintf((string)$text, $args) : (string)$text;
}

/** Cosa ha fatto una versione, a parole (cronologia e Da approvare). */
function cp_history_action(array $row, string $lang): string
{
    $w = cp_write_strings($lang);
    $kind = (string)$row['kind'];
    if ($kind === 'restore') {
        // Il ripristino si ricorda la data della versione rimessa; senza, la
        // voce è stata rimessa online dopo essere stata nascosta.
        $when = preg_match('~^\d{4}-\d{2}-\d{2}~', (string)$row['summary']) ? cp_format_date((string)$row['summary'], $lang, 'long') : '';
        return $when !== '' ? cp_w('restored_to', $lang, $when) : $w['unhid'];
    }
    return $w['kinds'][$kind] ?? $kind;
}

/** Il messaggio di chi ha scritto una versione (il ripristino non ne ha). */
function cp_history_summary(array $row): string
{
    return $row['kind'] === 'restore' ? '' : trim((string)$row['summary']);
}

